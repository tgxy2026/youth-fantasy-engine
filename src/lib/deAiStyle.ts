// 【为什么要有这个文件】2.6.4 之前，「去 AI 味」的规则散在两处且口径不一：
//   · `aiTasks/inline.ts` 的 `DEAI_INLINE_RULE`（伴写·生成向，7 行口语化描述）；
//   · `autoContinue.ts` 的 `DEAI_SYS` + `DEAI_TEMPLATES`（连写·改写向，4 套提示词）。
// 两处各写各的，改一处另一处不动；而整章改写 / 灵感转正文 / 续写初稿这些**同样产出正文**的
// 入口压根没挂。社区反馈「去 AI 味儿做得不理想」，根子就在这儿：规则本身也太粗，
// 只有"不要用套话、不要堆排比"这种正确但不可执行的口号。
//
// 本文件按 2026-10-02 联网调研的结果重写（中文网文场景的实证词表 + 英文侧 de-slop 研究），
// 落成**三类可执行的判据**：词（哪些词是模板）→ 句（哪些句式是模板）→ 段（节奏与结构）。
// 所有生成正文的入口都从这里取，改一处全生效。
//
// 🔴🔴 **立场（不要改）**：这是**文风质量**功能 —— 目的是让 AI 出的文字更像职业作者的手笔、
//    可读可信、不劝退读者。**不承诺、不声称、也不以绕过任何平台的 AIGC 检测为目标**；
//    界面与文档都不得写成"过检测""降 AI 率"。产品只做创作辅助与质量自检。
//
// 🔴 **使用纪律（来自本项目实测）**：反重复 / 去 AI 味的提示词**只有钉在 system 末尾才有效**，
//    埋在中段效果约等于 0（酒馆模式实测）。所以 `deAiGenerateRule()` 的返回值一律**追加在最后**。

