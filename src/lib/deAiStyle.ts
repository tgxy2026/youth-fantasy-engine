/** 二级词：单个出现无罪，**通篇都是**才是病 —— 成片出现就该砍掉六成 */
export const DEAI_TELL_SOFT: string[] = [
  '突然', '瞬间', '霎时', '骤然', '蓦地', '陡然', '与此同时', '不由自主', '情不自禁', '自然而然',
  '不容置疑', '显而易见', '毫无疑问', '不可否认', '不易察觉', '深吸一口气', '一丝', '一抹', '些许', '几分',
]

/** 句式模板：比单词更致命 —— 词换了、架子还在，读者照样一眼认出 */
export const DEAI_TELL_PATTERNS: string[] = [
  '「…带着一丝…」这种万能状语（"他说，带着一丝无奈"）',
  '「眼中闪过一丝XX」「嘴角勾起一抹XX」「心中涌起一股XX」这类填空式描写',
  '「像刀子一样锋利」这种陈词比喻；一句话里堆三个比喻、四个形容词',
  '「他感到…」「她意识到…」—— 直接告知情绪，而不是把它演出来',
  '连续三句以上同结构排比（"有的…有的…有的…"；"他知道…他明白…他清楚…"）',
  '「首先 / 其次 / 最后」的三段式，以及凡事都凑成三条',
  '段末的标准总结与升华（"这一刻，他终于明白…""原来…""一切…都…"）',
  '「不是X，而是Y」的否定对照句式反复出现（一次还行，隔几段就来就是病）',
  '「就在这时」「正当…之际」「然而下一刻」这类套路转折 —— 读者一看到就知道后面要反转',
]

/** 正面原则：不是"不要做什么"，而是"该往哪儿写" —— 只有禁令的话模型会写成干巴巴的干净句子 */
export const DEAI_PRINCIPLES: string[] = [
  '情绪用动作与身体感受演出来：写「她把手心的汗往裤子上擦了擦，端杯子时发现手在抖」，不写「她非常紧张」',
  '抽象形容换成能被"拍下来"的具体画面与五感细节（触觉、气味、温度、耳边杂音），别只给概括',
  '句式长短错落：连续三句差不多长就重写第三句；段落长短也要不齐（有的段一两句，有的七八句）',
  '对话要有省略、停顿、半句话、口头禅与潜台词，别让每句都逻辑完整、滴水不漏',
  '允许一点"不完美"：碎片化的破句（「他不想听。真的不想。一个字都不想。」）、偶尔的题外话或自我修正',
  '加一点"无意义但真实"的生活细节（摸出半包烟只剩一根、点上发现打火机没气了）',
  '段末不要总结升华，收在一句有分量的具体动作或台词上',
  '不写空泛的哲理感慨，不用「意义深远」「前所未有」这类只表态不信息的词',
]

/** 免责说明（🔴 必须跟着词表一起给模型，否则它会机械清词、把文风洗坏） */
export const DEAI_CAVEAT =
  '上面是「候选清单，不是删除令」：这些词句本身无罪（经典文学里也满地都是），判据是「通篇是不是都在用」。' +
  '确有必要、换了反而伤文风的就照旧 —— 宁可留一处自然的「缓缓」，也不要为了清词把句子改得佶屈聱牙。'

function bullets(items: string[]): string {
  return items.map(x => `· ${x}`).join('\n')
}

function wordTable(): string {
  const parts: string[] = []
  for (const [group, words] of Object.entries(DEAI_TELL_HARD)) parts.push(`${group}：${words.join('、')}`)
  parts.push(`成片出现就该砍的：${DEAI_TELL_SOFT.join('、')}`)
  return bullets(parts)
}

/**
 * **生成向**规则（写新正文时用）—— 必须追加在 system **末尾**。
 *
 * @param scope 'brief' = 伴写这种"只续一两句话"的粒度，规则必须短，否则把正文要求挤没了；
 *              'full'  = 整章生成 / 整章改写，给完整版。
 */
export function deAiGenerateRule(scope: 'brief' | 'full' = 'full'): string {
  if (scope === 'brief') {
    return `【文风纪律 · 最重要】
不要用「仿佛 / 似乎 / 宛如 / 不禁 / 微微 / 缓缓 / 心中暗道 / 眼中闪过一丝 / 嘴角勾起一抹」这类 AI 高频套话；
不要写「他感到…」「她意识到…」这种直接贴情绪标签的句子 —— 把情绪演成动作、身体感受或一句台词；
不要堆四字成语、对称排比与「首先/其次/最后」；不要写空泛的总结、升华或哲理感慨；
不要复述或换皮重复前文已经写过的句子、动作、意象与比喻 —— 同一表达只用一次，直接推进新的内容；
多给具体的动作、对白与感官细节，句子长短错落，像活人顺手写下来的。`
  }
  return `【文风纪律 · 最重要（钉在最后，优先于前面一切风格要求）】

一、这些词是模板，成片出现就是 AI 腔：
${wordTable()}

二、这些句式比单词更致命（换了词、架子还在，读者照样一眼认出）：
${bullets(DEAI_TELL_PATTERNS)}

三、该往哪儿写：
${bullets(DEAI_PRINCIPLES)}

四、${DEAI_CAVEAT}

五、不要复述或换皮重复前文已经写过的句子、动作、意象与比喻 —— 同一表达只用一次，直接推进新的内容。`
}

/**
 * **改写向**条款（润色已有正文时用）—— 与 `deAiGenerateRule` 的区别是它面向"手上已有稿子"，
 * 所以额外强调"只改怎么说、不改说什么"，以及改完要自检。
 */
export function deAiPolishClause(): string {
  return `一、这些词是模板，成片出现就是 AI 腔：
${wordTable()}

二、这些句式比单词更致命（换了词、架子还在，读者照样一眼认出）：
${bullets(DEAI_TELL_PATTERNS)}

三、该往哪儿改：
${bullets(DEAI_PRINCIPLES)}

四、${DEAI_CAVEAT}

五、改完自检：情节 / 人设 / 专名 / 对话内容有没有被改坏？同一段里有没有连续三句同样长？
有没有只剩下干巴巴的干净句子、把原来的画面感也一起删掉了？`
}
