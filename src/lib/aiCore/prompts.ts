/**
 * 补全的**语境** —— 决定这次发哪条系统提示词。
 * · `'template'`（缺省）＝ 通用设定补全（表单页 / 角色卡 / 表格行）；
 * · `'outline-master'` / `'outline-volume'` / `'outline-chapter'` ＝ 大纲规划组三页签
 *   （全书总纲 / 分卷大纲 / 章节细纲）。
 * 用户消息（字段清单 + 上下文 + 草图 + 返回 JSON）四条通用，不必各写一份。
 */
export type FillContext = 'template' | 'outline-master' | 'outline-volume' | 'outline-chapter'

/** 语境 → 提示词。声明在上面几个 `let` **之后**（读值发生在调用期，不是这里） */
export const FILL_CONTEXT_SYS: Record<FillContext, () => string> = {
  template: () => P_fill_template,
  'outline-master': () => P_fill_outline_master,
  'outline-volume': () => P_fill_outline_volume,
  'outline-chapter': () => P_fill_outline_chapter,
}

