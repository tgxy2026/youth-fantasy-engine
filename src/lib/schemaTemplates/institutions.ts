/**
 * 取该题材下的模块定义（**示例已按题材替换**）。
 *
 * 🔴 落库键仍是 `模块名::字段名`，**题材切换不会丢数据**：换包只换掉字段定义里 `example`
 *    这一层（给作者看的填写示范），`desc` 与字段名一模一样 ⇒ 换回来内容照旧在。
 *
 * @param pack 当前项目题材（未列入覆盖表的题材，如东方修真 ⇒ 原样返回默认示例）
 */
export function institutionModules(pack: GenrePack): FormModule[] {
  return Object.values(INSTITUTION_MODULES).flatMap(mods => withExamples(mods, EXAMPLES_BY_PACK[pack]))
}

/**
 * 按示例覆盖表替换某页签内各字段的 `example`（纯函数：新建对象，**不改原定义**）。
 * 只覆盖表里列出的字段，其余原样。
 */
function withExamples(modules: FormModule[], map?: ExampleMap): FormModule[] {
  if (!map) return modules
  return modules.map(m => ({
    name: m.name,
    fields: m.fields.map(f => (map[f.name] ? { ...f, example: map[f.name] } : f)),
  }))
}

/**
 * 🔴 只给**某一个制度页签**取模块（`modulesFor` 需要按 tabId 取，不能一次拿全部）。
 * @param tabId `politics` / `economy` / `belief` / `justice`
 */
export function institutionModulesOf(tabId: string, pack: GenrePack): FormModule[] | undefined {
  const mods = INSTITUTION_MODULES[tabId]
  if (!mods) return undefined
  return withExamples(mods, EXAMPLES_BY_PACK[pack])
}

