/**
 * 四个制度页签的模块定义 —— 政治架构 / 经济体系 / 宗教信仰 / 司法制度（2.7.1 · §8.4）。
 *
 * ## 为什么这四个页签**不分题材包**
 * 「世界设定 / 力量体系」按题材包换模块，是因为它们的内容**强题材绑定**
 * （境界阶梯 ↔ 魔法学派 ↔ 官阶品级）。
 * 而制度维度（政体怎么运转、钱怎么流通、信什么神、按什么法判）是**跨题材通用**的：
 * 科幻的政治架构与历史的政治架构，问的是同一批问题。
 *
 * 所以这四个页签**一套定义**，题材差异通过两条机制解决：
 *   · **显隐**：`packs.packShowsTab` 决定哪些题材默认显示（历史古代四个制度页签全开、修真全关），
 *     被隐藏的可在「世界设定」页头部「页签」控件按需补开；
 *   · **多份**：页签自带**并列结构**（`PARALLEL_SET_TABS`，2.7.2）—— 一个政权 / 一个邦国建一条，
 *     每条各写各的（**没有「全书统一」那一层**，2.7.2 主人定案取消母级）。
 *     每条带一个「活跃 / 已完结」开关，只有活跃的才发给 AI。
 *
 * ## 与「世界设定」的分工（防重叠，§8.6）
 * · `worldbase` ＝ **这个世界长什么样**（总览 / 社会 / 成长地图 / 钩子）
 * · `politics` 等 ＝ **这个世界怎么运转**（制度细节）
 * 两者字段的 desc 互相指路，避免「同一件事填两遍」时不知道该填哪。
 */
