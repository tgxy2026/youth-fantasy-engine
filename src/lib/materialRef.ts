// 素材资料：内置只读写作参考库。
// 设计目标：按「分类(category) → 板块(block) → 数据」三级组织，
// 后续新增通用写作参考（如世界观模板、情节套路等）只需往 MATERIAL_CATEGORIES 追加一个 category，
// 组件已按 block.kind 通用渲染，无需改动 UI 代码。
// 所有内容均为只读，用户不可编辑。

export type BlockKind =
  | 'charGrid' // 性格类型卡片网格（含性别筛选 / 搜索）
  | 'list' // 编号 / 普通列表
  | 'combo' // 混搭组合：A × B = 结果
  | 'table' // 表格（表头 + 行）
  | 'tagGroups' // 标签分组云
  | 'attrs' // 萌属性：名 + 说明
  | 'roles' // 故事功能角色列表
  | 'groupedList' // 分组列表（如 补充类型 女 / 男）
  | 'toolbox' // 工具箱：多小节

export interface CharDim {
  label: string
  value: string
}

export interface CharType {
  id: string
  name: string
  gender: '女' | '男'
  tagline: string // 一句话标签（如 端庄·分寸感）
  fit: string[] // 适配定位（徽章）
  dims: CharDim[] // 8 维（核心气质 … 避雷；适配定位已单列 fit）
}

export interface ComboItem {
  a: string
  b: string
  result: string
}

export interface RoleItem {
  name: string
  desc: string
}

export interface TagGroup {
  group: string
  tags: string[]
}

export interface AttrItem {
  name: string
  desc: string
}

export interface ToolboxSection {
  title: string
  formula?: string
  example?: string
  items?: { label?: string; text: string }[]
}

export interface Block {
  id: string
  title: string
  kind: BlockKind
  data: any
}

export interface MaterialCategory {
  id: string
  name: string
  blocks: Block[]
}

// 性格类型 9 维模板（顺序固定，适配定位单列 fit，故 dims 取前 8 维）
export const CHAR_DIM_ORDER = ['核心气质', '造型符号', '动作微表情', '语言习惯', '行为逻辑', '情感表达', '反差矛盾点', '避雷']

function ct(
  id: string,
  name: string,
  gender: '女' | '男',
  tagline: string,
  fit: string,
  d: Record<string, string>,
): CharType {
  return {
    id,
    name,
    gender,
    tagline,
    fit: fit.split('、').map(s => s.trim()).filter(Boolean),
    dims: CHAR_DIM_ORDER.map(label => ({ label, value: d[label] })),
  }
}

