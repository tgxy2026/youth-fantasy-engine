  //       那是「两个透明层同层 + 正文压其上」的**盒模型对齐约定**（红线：双图层盒模型必须逐项
  //       一致）。这里的 `0` 不是层号刻度，而是「同一层的两支」，换成常量反而会让人以为它可调。
  //    ② 时间线组件内部的 `SVG(0) → 卡片(10) → 圆点(11)` —— 组件内固定关系，`11` 对外无意义。
  //    ③ 「配对型」布局里成对出现的正负层：背景走 pageBackdrop，它的内容容器走 pageHandle。
