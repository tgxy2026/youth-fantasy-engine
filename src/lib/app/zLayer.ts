  //    Tooltip 一旦拿到全站层号，就会出现「Tooltip 盖住弹窗」「页内面板压住右下角保存球」。
  //    所以收敛到 Z 里，但沿用原来的数字（零视觉变更）。
  //
  // 🔴 2026-09-23（六维审计）把**页内定位元素**也收了进来 —— 原先它们散在 10 个文件里手写
  //    className 的 `-z-10` / `z-10` / `z-20`，想统一调一次得翻遍全项目。数值**逐个照抄**。
