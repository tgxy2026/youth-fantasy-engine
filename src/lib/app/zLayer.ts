  /** 弹窗内嵌弹窗（如设置弹窗里再弹一层） */
  modalNested: 2100,
  /** PromptModal / confirmDialog：需盖住任何 modal */
  prompt: 3000,

  // ---- 常驻角标层：项目内一直挂着的浮动控件 ----
  //
  // ⚠️ 这几个数字**必须远低于 modal**（2000）：它们常驻页面，若高于弹窗就会出现
  //    「弹窗开着、右下角保存球却压在弹窗上」的怪象。原先散落写成 z-20 / z-40 / z-50，
  //    2026-09-17 审计收敛到这里，往后新增角标一律从这里取。
  /** 右下角保存悬浮球 SaveFab */
  fab: 20,
  /** 左下角 DataDock（项目内唯一允许的左下浮层）；DesktopDataBar 的非内嵌兜底形态同层 */
  dock: 40,
  /** 侧边看板娘：结文记精灵 / 项目中心右下角那位 */
  sprite: 40,
  /**
   * U-5 · 2.6.0：桌面写入锁横幅（DesktopWriteLockBanner）—— 常驻级**顶部状态条**。
   * 高于页面常驻（fab/dock/sprite），但**低于 modal**：它是持久状态条而非交互弹层，
   * 弹窗打开时被盖住可接受（弹窗操作本来也写不了盘）；原先错借 Z.dropdown(9999)
   * 会压住所有弹窗与 toast，属语义错位（2026-09-27 巡检 U-5）。
   * 便携写入锁横幅（PortableWriteLockBanner）同层共用（2026-10-10 便携版 WP-2b）。
   */
  banner: 60,

  // ---- 以下为「浮层」层，全部 createPortal 到 body ----
  //
  // ⚠️ 为什么下拉要**高于** modal 与 prompt，而不是像直觉那样排在它们下面：
  //   这些下拉会出现在**弹窗内部**——例如 AIOrganize 本身就是一个 Modal，其中用了
  //   CustomSelect / resolveOptions；表格单元格的日期、日历选择也可能位于编辑弹窗内。
  //   它们既已 Portal 到 body，只是把层号降到 modal 之下，弹窗内的下拉就会被弹窗盖住
  //   而完全不可用。故维持「浮层在弹窗之上」这一既有约定。
  //
  // 📌 已知张力（未擅自改动，留待需要时决定）：prompt(3000) 目前低于下列浮层，
  //    理论上「下拉展开时又弹出确认框」会出现确认框被下拉遮住的情况；因下拉随失焦/外部
  //    点击即刻收起，实际极少同时出现。若要收紧，把 prompt 提到 dropdown 之上即可——
  //    现在只需改这一处。
  /** 下拉浮层：CustomSelect / CharacterSelect / TableRefSelect / CalendarPicker */
  dropdown: 9999,
  /** 帮助气泡 HelpPopover：略高于下拉，避免被邻近下拉压住 */
  popover: 10000,
  /** 轻提示 showToast：与帮助气泡同层 */
  toast: 10000,
  /** 下拉内再套下拉（如日期选择弹层里的日历体系选择器） */
  dropdownNested: 10001,

