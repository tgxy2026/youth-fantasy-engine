/**
 * 提示词里「单个单元格最多带多少字」（3.1.3 从事发地 `aiContext` 抽出来的纯数据 + 纯函数）。
 *
 * 为什么单独成文件：`aiContext.ts` 已贴着 1200 行结构闸，而这里是一张**字段名单**，
 * 与装配逻辑无关（装配那套是状态机，这份是常量表）。混在一起只会让两边都难找。
 *
 * 🔴 两条口径，别写反：
 *   1. **内置列**按名单放宽（`LONG_FIELDS`）—— 名单的意义是「它天生就该长」，
 *      不是「所有长文本都放宽」：像「备注」这种宽泛字段，给 600 字会把预算吃光。
 *   2. **自定义字段**按**类型**放宽（`longText` → 600）—— 它们的存储键是 `cf_*`，
 *      永远不可能出现在名单里，只能靠类型判断。
 *      （3.1.3 之前漏了第 2 条：作者建的长文本字段写了 800 字，模型只看到前 200 字。）
 */

/** 普通字段的字符上限 */
export const CELL_CAP = 200
/** 天生就该长的字段的字符上限 */
export const CELL_CAP_LONG = 600

/**
 * 天生就该长的内置字段：真相 / 派系斗争 / 关系演变 / 事件链这类自由文本。
 * 按 200 字截断的后果是模型只看到半句，反而容易"接着半句往下编" —— 故单独放宽。
 * 按**字段名**判定（schema 列名即存储键，全库同名同义）。
 */
const LONG_FIELDS = new Set([
  '事件经过（真相）', '民间流传版本（vs真相）', '事件链（起→承→转→合）',
  '内部派系与权力斗争', '演变轨迹（按卷）', '演变触发事件',
  '经济来源', '历史沿革', '对外关系',
  '核心矛盾/内在挣扎', '关键过往经历', '核心性格',
  '距离与行程时间', '地貌与气候', '范围与面积',
  '世界终极真相', '隐藏设定', '体系背后的世界观真相', '体系的隐藏层级',
  '回收方式与效果', '回收前置条件',
  '镇派功法/核心武力', '实力与功法',
])

/**
 * 取某字段的字符上限。
 * @param name 存储键（内置＝列名，自定义＝`cf_*`）
 * @param customType 自定义字段的类型；内置字段不传
 */
export function cellCap(name: string, customType?: 'text' | 'longText' | 'number' | 'select' | 'multiSelect' | 'boolean'): number {
  if (customType === 'longText') return CELL_CAP_LONG
  return LONG_FIELDS.has(name) ? CELL_CAP_LONG : CELL_CAP
}
