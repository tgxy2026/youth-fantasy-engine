  //      AI 注入也不带它（`splitActive` 只挑活跃的）。
  //   ③ 落库键仍是「模块名::字段名」（与表单型同口径），写错界面就一片空白
  //      ⇒ 由 `tests/seed-schema-check.mjs` 与 `tests/seedRef.test.ts` 双向闸住。
