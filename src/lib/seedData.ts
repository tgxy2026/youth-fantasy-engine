function fieldKey(tabId: string, fieldName: string): string {
  const tab = TABS.find(t => t.id === tabId)
  if (!tab?.modules) throw new Error(`tab not found: ${tabId}`)
  for (const m of tab.modules) {
    if (m.fields.some(f => f.name === fieldName)) return `${m.name}::${fieldName}`
  }
  throw new Error(`field not found: ${tabId} / ${fieldName}`)
}

/** 表单型页签：每个字段填入 schema 示例值（即 Excel 3.1 的黄色示例行） */
function formByExamples(tabId: string, overrides: Record<string, string> = {}): Record<string, string> {
  const tab = TABS.find(t => t.id === tabId)
  const data: Record<string, string> = {}
  if (!tab?.modules) return data
  for (const m of tab.modules) {
    for (const f of m.fields) data[`${m.name}::${f.name}`] = f.example
  }
  for (const [name, val] of Object.entries(overrides)) data[fieldKey(tabId, name)] = val
  return data
}

function card(tabId: string, name: string, order: number, overrides: Record<string, string> = {}): CardRecord {
  return { id: uid(), projectId: '', tabId, name, data: formByExamples(tabId, overrides), order }
}

function row(tabId: string, order: number, data: Record<string, string>): TableRow {
  return { id: uid(), projectId: '', tabId, data, order }
}

