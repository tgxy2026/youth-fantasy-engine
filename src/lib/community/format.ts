/**
 * 投稿广场 · 展示格式（3.6.2）
 *
 * 抽成独立模块的唯一理由：**同一串数字会在列表、详情、合集页三处出现**，
 * 三处各写一份格式化，早晚会出现"列表说 1.2 万、合集页说 12345"。
 */

/**
 * 浏览量显示。
 * · 一万以下原样显示（读者对 8423 这种数有感知）；
 * · 过万折成「1.2 万」；
 * · 十万以上不再保留小数（「12 万」比「12.3 万」更好读，且这个量级精度已无意义）。
 *
 * 🔴 不做"四舍五入到整数万"：10400 与 19400 都显示「1 万」会让人以为数字没动。
 */
export function formatViews(n: number | undefined | null): string {
  const v = Number(n) || 0
  if (v < 0) return '0'
  if (v < 10000) return String(Math.floor(v))
  const w = v / 10000
  return `${w.toFixed(v >= 100000 ? 0 : 1)} 万`
}
