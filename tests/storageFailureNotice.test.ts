import assert from 'node:assert/strict'
import { createStorageFailureNotice } from '../src/lib/app/storageFailureNotice'
import type { StorageWriteFacts } from '../src/lib/app/storageWriteStatus'
const facts = (over: Partial<StorageWriteFacts> = {}): StorageWriteFacts => ({ connected: true, dirty: true, saving: false, lastError: 'private-path.tmp/token=secret', lastSavedAt: 0, ...over })
const notice = createStorageFailureNotice()
const first = notice(facts(), 'owner-a')
assert.ok(first?.includes('存储区') && !first.includes('private') && !first.includes('token'))
console.log('PASS safe actionable first failure')
for (let i = 0; i < 30; i++) assert.equal(notice(facts({ lastError: `unique-temp-${i}.tmp` }), 'owner-a'), null)
console.log('PASS native retries with unique temporary paths do not flood notices')
assert.equal(notice(facts({ lastError: '', saving: true }), 'owner-a'), null)
assert.equal(notice(facts(), 'owner-a'), null)
assert.equal(notice(facts({ lastError: '', saving: false }), 'owner-a'), null)
assert.equal(notice(facts(), 'owner-a'), null)
console.log('PASS transient retry/pending states do not re-arm an unresolved failure')
assert.equal(notice(facts({ lastError: '', dirty: false, lastSavedAt: 1 }), 'owner-a'), null)
assert.ok(notice(facts(), 'owner-a'))
console.log('PASS a clean backend receipt re-arms a later failure episode')
assert.ok(notice(facts({ writeLocked: true }), 'owner-a')?.includes('暂停'))
assert.equal(notice(facts({ writeLocked: true }), 'owner-a'), null)
assert.ok(notice(facts({ saveConflict: true }), 'owner-a')?.includes('冲突'))
console.log('PASS changed failure categories retain their distinct recovery instructions')
assert.ok(notice(facts(), 'owner-b'))
assert.equal(notice(facts(), 'owner-b'), null)
console.log('PASS replacement storage receives its own notice without old private payloads')
const clean = createStorageFailureNotice()
assert.equal(clean(facts({ connected: false, lastError: '' })), null)
assert.equal(clean(facts({ lastError: '', saving: true })), null)
console.log('PASS connecting/pending states do not invent failures')
const recovery = createStorageFailureNotice()
recovery(facts())
assert.ok(recovery(facts({ lastError: 'SESSION_REPLACED private-token' }))?.includes('已在别处登录'))
const expired = recovery(facts({ lastError: '登录已过期 private-token' }))
assert.ok(expired?.includes('登录已过期') && expired.includes('复制') && !expired.includes('private'))
console.log('PASS changed authentication reasons survive sanitization and deduplication')
assert.ok(recovery(facts({ lastError: 'HTTP 413 private-path' }))?.includes('配额'))
assert.equal(recovery(facts({ lastError: 'QUOTA_EXCEEDED different-private-path' })), null)
console.log('PASS quota aliases share one safe failure episode')
assert.ok(recovery(facts({ lastError: 'EPERM private-file.123.tmp' }))?.includes('权限'))
assert.equal(recovery(facts({ lastError: 'EPERM private-file.124.tmp' })), null)
console.log('PASS native temporary-path churn remains bounded with specific recovery guidance')
